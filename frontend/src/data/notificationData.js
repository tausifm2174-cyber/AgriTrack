/**
 * Calculates summary metrics from a notification dataset
 * @param {Array} list 
 * @returns {Object}
 */
export function getNotificationSummary(list = []) {
  const total = list.length;
  const unread = list.filter((n) => !n.isRead).length;
  const warnings = list.filter((n) => n.severity === 'WARNING').length;
  const critical = list.filter((n) => n.severity === 'CRITICAL').length;
  const info = list.filter((n) => n.severity === 'INFO').length;
  const success = list.filter((n) => n.severity === 'SUCCESS').length;

  return {
    total,
    unread,
    warnings,
    critical,
    info,
    success,
  };
}
