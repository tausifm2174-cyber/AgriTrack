/**
 * Calculates dynamic summary counts from activities list
 * @param {Array} list
 * @returns {Object}
 */
export function getActivitySummary(list = []) {
  const total = list.length;
  const planned = list.filter((a) => a.status === 'Planned').length;
  const inProgress = list.filter((a) => a.status === 'In Progress').length;
  const completed = list.filter((a) => a.status === 'Completed').length;
  const cancelled = list.filter((a) => a.status === 'Cancelled').length;

  return {
    total,
    planned,
    inProgress,
    completed,
    cancelled,
  };
}
